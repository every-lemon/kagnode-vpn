#!/usr/bin/env python3
"""Build minified VPN browser code; no runtime Node dependency."""
import ast,hashlib,json,os,subprocess,tempfile
from pathlib import Path

root=Path(__file__).resolve().parents[1]
module=ast.parse((root/'src/vpn_admin.py').read_text())
source={}
for node in module.body:
    if isinstance(node,ast.Assign):
        for target in node.targets:
            if isinstance(target,ast.Name) and target.id in ('STYLE','SCRIPT'):
                source[target.id]=ast.literal_eval(node.value)
    elif isinstance(node,ast.AugAssign) and isinstance(node.target,ast.Name) and node.target.id=='STYLE':
        source['STYLE']+=ast.literal_eval(node.value)
source['STYLE']+='\n'+(root/'web/kagnode-ui.css').read_text()+'\n'+(root/'web/product.css').read_text()
source['STYLE']+='\n'+(root/'web/kagnode-scroll.css').read_text()
source['SCRIPT']=(root/'web/kagnode-scroll.js').read_text()+'\n'+(root/'web/theme.js').read_text()+'\n'+source['SCRIPT']
compiled={};hashes={}
with tempfile.TemporaryDirectory(prefix='kagnode-vpn-ui-') as folder:
    for key,extension in [('STYLE','css'),('SCRIPT','js')]:
        path=Path(folder)/('input.'+extension);path.write_text(source[key]);target=Path(folder)/('output.'+extension)
        subprocess.run([os.environ.get('ESBUILD','esbuild'),str(path),'--minify','--target=es2020','--charset=utf8','--legal-comments=inline','--banner:'+extension+'=/*! KagNode. VPN | Source and license: see project repository. */','--outfile='+str(target)],check=True,capture_output=True)
        compiled[key]=target.read_text();hashes[key]=hashlib.sha256(target.read_bytes()).hexdigest()
output='# Generated by scripts/build-web.py. Readable UI source is retained.\n'
output+='\n'.join(key+' = '+repr(value) for key,value in compiled.items())+'\nUI_SHA256 = '+repr(hashes)+'\n'
(root/'src/vpn_ui_assets.py').write_text(output)
print('Built fingerprinted VPN CSS and JavaScript without source maps.')
